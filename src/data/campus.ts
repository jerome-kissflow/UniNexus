export function groupsFor(studentId: string, groups: CampusGroup[]) {
  return groups.filter((g) => g.members.includes(studentId))
}

export function feedFor(studentId: string, groups: CampusGroup[], posts: CampusPost[]) {
  const ids = new Set(groupsFor(studentId, groups).map((g) => g.id))
  return posts.filter((p) => ids.has(p.groupId)).sort((a, b) => (a.at < b.at ? 1 : -1))
}
